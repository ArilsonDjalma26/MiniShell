#include "../minishell.h"

void    skipe_space(const char *input, int *i)
{
    while(input[*i] == ' ' || input[*i] == '\t')
        (*i)++;
}
int is_operator(char c)
{
    return(c == '|' || c == '<' || c == '>');
}